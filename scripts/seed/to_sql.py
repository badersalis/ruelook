"""catalog.json -> supabase/seed/catalog.sql: one compact, idempotent statement driven by a jsonb literal.

Products upsert by slug; colours/variants/images are inserted only for products that have none yet
(no destructive statements). Run: python scripts/seed/to_sql.py, then apply the SQL.
"""
import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
d = json.load(open(os.path.join(ROOT, "supabase", "seed", "catalog.json"), encoding="utf-8"))

rows = [
    {
        "s": p["slug"], "n": p["name"], "c": p["category"], "d": p["description"], "m": p["material_care"],
        "p": p["price_cents"], "a": p["days_ago"] * 86400 + p["price_cents"] % 997,
        "cn": p["colour"], "hx": p["hex"],
        "v": [[size, stock] for size, stock in p["stock"].items()],
        "i": [[im["path"].replace("static/catalog/", "~"), im["alt"]] for im in p["images"]],
    }
    for p in d["products"]
]
payload = json.dumps(rows, ensure_ascii=False, separators=(",", ":")).replace("'", "''")

sql = f"""-- Generated by scripts/seed/to_sql.py. Demo data only.
insert into public.categories (slug, name, sort) values
  ('women','Women',1),('men','Men',2),('shoes','Shoes',3),('bags','Bags',4),('accessories','Accessories',5)
on conflict (slug) do update set name = excluded.name, sort = excluded.sort;

with src as (select value as r from jsonb_array_elements('{payload}'::jsonb)),
prod as (
  insert into public.products (slug, name, category_id, description, material_care, price_cents, status, drop_label, created_at)
  select r->>'s', r->>'n', c.id, r->>'d', r->>'m', (r->>'p')::int, 'published', 'Drop 07',
         now() - make_interval(secs => (r->>'a')::int)
  from src join public.categories c on c.slug = r->>'c'
  on conflict (slug) do update set name = excluded.name, category_id = excluded.category_id,
    description = excluded.description, material_care = excluded.material_care,
    price_cents = excluded.price_cents, status = excluded.status, drop_label = excluded.drop_label
  returning id, slug
),
fresh as (
  select prod.id, src.r from prod join src on src.r->>'s' = prod.slug
  where not exists (select 1 from public.product_colors pc where pc.product_id = prod.id)
),
col as (
  insert into public.product_colors (product_id, name, hex, sort)
  select id, r->>'cn', r->>'hx', 0 from fresh
  returning id, product_id
),
var as (
  insert into public.product_variants (product_id, color_id, size, stock)
  select f.id, col.id, v->>0, (v->>1)::int
  from fresh f join col on col.product_id = f.id, jsonb_array_elements(f.r->'v') v
  returning 1
)
insert into public.product_images (product_id, path, alt, sort)
select f.id, replace(im.value->>0, '~', 'static/catalog/'), im.value->>1, (im.ordinality - 1)::smallint
from fresh f, jsonb_array_elements(f.r->'i') with ordinality im;
"""
path = os.path.join(ROOT, "supabase", "seed", "catalog.sql")
open(path, "w", encoding="utf-8").write(sql)
print(path, len(sql), "bytes")
