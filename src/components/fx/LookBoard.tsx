"use client";

/**
 * "Complete the look" assembly (signature interaction 2, board S3).
 * Spec: docs/design/ux-spec.md §4, docs/design/prototypes/README.md §1.
 *
 * Presentation and motion only: the caller owns data fetching, the size sheet and the cart.
 * - Before JS (and before the board scrolls into view) it is a plain list plus rationale.
 * - On first view (35% visible) and on each look switch, items slide in from the side they sit
 *   on (60 ms stagger) and seeded SVG connectors draw in (stroke-dashoffset, motion.draw).
 * - Reduced motion: items fade in place (120 ms), connectors are static. Capture mode: final
 *   state instantly, fixed per-look seed.
 */

import Link from "next/link";
import {
  useCallback,
  useEffect,
  useId,
  useLayoutEffect,
  useRef,
  useState,
  type KeyboardEvent as ReactKeyboardEvent,
  type ReactNode,
} from "react";
import type { Look, ProductImage, ProductSummary } from "@/lib/types";
import { imageUrl } from "@/lib/config";
import { DUR, EASE, allFinished, canAnimate, staggerDelay } from "@/lib/fx/motion";
import { prefersReducedMotion } from "@/lib/fx/reducedMotion";
import { useCaptureMode } from "@/lib/fx/capture";
import { buildConnectors, type TileBox } from "@/lib/fx/connectors";
import { lookSeed } from "@/lib/fx/rng";

export interface LookBoardProps {
  current: ProductSummary;
  looks: Look[];
  onQuickAdd: (p: ProductSummary) => void;
  onAddAll: (items: ProductSummary[]) => void;
  loading?: boolean;
  error?: string | null;
  onRetry?: () => void;
  footerSlot?: ReactNode;
}

export const AI_TOOLTIP = "Looks are generated by an AI model from our catalogue. Check sizes before you buy.";
export const STYLIST_ERROR = "The stylist is taking a break. Try again.";

const usd = new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" });
export const formatUSD = (cents: number) => usd.format(cents / 100);

const SVGNS = "http://www.w3.org/2000/svg";

function primaryImage(p: ProductSummary): ProductImage | undefined {
  return [...p.images].sort((a, b) => a.sort - b.sort)[0];
}
export const productHref = (slug: string) => `/product/?slug=${encodeURIComponent(slug)}`;
const inStock = (p: ProductSummary) => p.totalStock > 0;

/** Items "Add the full look" sends: this piece first, then the look, minus sold-out and duplicates. */
export function addableItems(current: ProductSummary, look: Look | undefined): ProductSummary[] {
  const seen = new Set<string>();
  return [current, ...(look?.items ?? [])].filter((p) => {
    if (!inStock(p) || seen.has(p.id)) return false;
    seen.add(p.id);
    return true;
  });
}

/* Layout boxes relative to the board. offset* ignore transforms, so mid-animation is safe. */
function tileBox(el: HTMLElement): TileBox {
  const tile = el.querySelector<HTMLElement>(".fx-board__tile");
  return { x: el.offsetLeft, y: el.offsetTop, w: el.offsetWidth, h: el.offsetHeight, tileH: tile?.offsetHeight ?? el.offsetHeight };
}

/** Rebuild the connector overlay imperatively (React renders the <svg> empty and never touches its children). */
function drawConnectors(board: HTMLElement, svg: SVGSVGElement, seed: number): void {
  const anchor = board.querySelector<HTMLElement>("[data-look-anchor]");
  const items = Array.from(board.querySelectorAll<HTMLElement>("[data-look-item]"));
  svg.replaceChildren();
  if (!anchor || items.length === 0 || board.clientWidth === 0) return;
  svg.setAttribute("viewBox", `0 0 ${board.clientWidth} ${board.clientHeight}`);
  const conns = buildConnectors(tileBox(anchor), items.map(tileBox), seed);
  for (const c of conns) {
    const g = document.createElementNS(SVGNS, "g");
    const path = document.createElementNS(SVGNS, "path");
    path.setAttribute("d", c.d);
    const c0 = document.createElementNS(SVGNS, "circle");
    c0.setAttribute("cx", String(c.p0.x));
    c0.setAttribute("cy", String(c.p0.y));
    c0.setAttribute("r", "3");
    const c1 = document.createElementNS(SVGNS, "circle");
    c1.setAttribute("cx", String(c.p1.x));
    c1.setAttribute("cy", String(c.p1.y));
    c1.setAttribute("r", "3");
    c1.setAttribute("data-end", "");
    g.append(path, c0, c1);
    svg.append(g);
    if (typeof path.getTotalLength === "function") {
      const len = path.getTotalLength();
      // Real length (pathLength="1" is flaky in older Safari). Resting offset 0 = fully drawn.
      path.style.strokeDasharray = `${len} ${len}`;
      path.dataset.len = String(len);
    }
  }
}

export default function LookBoard({
  current,
  looks,
  onQuickAdd,
  onAddAll,
  loading = false,
  error = null,
  onRetry,
  footerSlot,
}: LookBoardProps) {
  const uid = useId();
  const titleId = `${uid}-title`;
  const tipId = `${uid}-tip`;
  const tabId = (i: number) => `${uid}-tab-${i}`;
  const panelId = `${uid}-panel`;

  const capture = useCaptureMode();
  const [selected, setSelected] = useState(0);
  const [tipOpen, setTipOpen] = useState(false);
  const sel = looks.length ? Math.min(selected, looks.length - 1) : 0;
  const look = looks[sel];
  const showBoard = !loading && !error && !!look;

  const boardRef = useRef<HTMLDivElement>(null);
  const svgRef = useRef<SVGSVGElement>(null);
  const rationaleRef = useRef<HTMLParagraphElement>(null);
  const tablistRef = useRef<HTMLDivElement>(null);
  const underlineRef = useRef<HTMLSpanElement>(null);
  const tabRefs = useRef<(HTMLButtonElement | null)[]>([]);
  const seenRef = useRef(false);
  const runningRef = useRef<Animation[]>([]);
  const captureRef = useRef(capture);
  useEffect(() => {
    captureRef.current = capture;
  }, [capture]);

  const cancelRunning = () => {
    runningRef.current.forEach((a) => a.cancel());
    runningRef.current = [];
  };

  /** Assembly choreography. Final (resting) styles equal the animation end states. */
  const enter = useCallback(() => {
    const board = boardRef.current;
    const svg = svgRef.current;
    cancelRunning();
    if (!board) return;
    delete board.dataset.waiting;
    if (captureRef.current || !canAnimate(board)) return;
    const anchor = board.querySelector<HTMLElement>("[data-look-anchor]");
    const lis = Array.from(board.querySelectorAll<HTMLElement>("[data-look-item]"));
    const anims: Animation[] = [];
    const why = rationaleRef.current;
    if (prefersReducedMotion() || !anchor) {
      const o: KeyframeAnimationOptions = { duration: DUR.reduced, easing: "linear", fill: "both" };
      lis.forEach((li) => anims.push(li.animate({ opacity: [0, 1] }, o)));
      if (svg) anims.push(svg.animate({ opacity: [0, 1] }, o));
      if (why) anims.push(why.animate({ opacity: [0, 1] }, o));
    } else {
      const A = tileBox(anchor);
      const acx = A.x + A.w / 2;
      const acy = A.y + A.h / 2;
      lis.forEach((li, k) => {
        const I = tileBox(li);
        const horiz = I.x + I.w <= A.x || I.x >= A.x + A.w;
        const dx = I.x + I.w / 2 - acx;
        const dy = I.y + I.h / 2 - acy;
        const from = horiz ? `translate(${Math.sign(dx) * 48}px, 0)` : `translate(0, ${(Math.sign(dy) || 1) * 32}px)`;
        anims.push(
          li.animate(
            { opacity: [0, 1], transform: [from, "translate(0, 0)"] },
            { duration: DUR.slow, delay: staggerDelay(k), easing: EASE.emphasized, fill: "both" },
          ),
        );
      });
      if (svg) {
        Array.from(svg.children).forEach((g, k) => {
          const path = g.querySelector<SVGPathElement>("path");
          const end = g.querySelector<SVGCircleElement>("[data-end]");
          const len = Number(path?.dataset.len ?? 0);
          const delay = DUR.drawDelay + staggerDelay(k);
          if (path && len > 0) {
            anims.push(
              path.animate(
                { strokeDashoffset: [len, 0] },
                { duration: DUR.draw, delay, easing: EASE.draw, fill: "both" },
              ),
            );
          }
          if (end) {
            anims.push(
              end.animate(
                { opacity: [0, 1] },
                { duration: DUR.reduced, delay: delay + DUR.draw - DUR.reduced, easing: "linear", fill: "both" },
              ),
            );
          }
        });
      }
      if (why) anims.push(why.animate({ opacity: [0, 1] }, { duration: DUR.base, easing: "linear", fill: "both" }));
    }
    runningRef.current = anims;
    void allFinished(anims).then(() => {
      if (runningRef.current !== anims) return;
      anims.forEach((a) => a.cancel());
      runningRef.current = [];
    });
  }, []);

  /* Build connectors and play the assembly whenever the visible look changes. */
  useLayoutEffect(() => {
    const board = boardRef.current;
    const svg = svgRef.current;
    if (!showBoard || !board || !svg) return;
    drawConnectors(board, svg, lookSeed(sel));
    if (seenRef.current) enter();
    else if (!captureRef.current && typeof IntersectionObserver === "function") board.dataset.waiting = "";
    return cancelRunning;
  }, [showBoard, sel, look, enter]);

  /* First view: assemble when 35% of the board is visible. */
  useEffect(() => {
    const board = boardRef.current;
    if (!showBoard || !board || seenRef.current) return;
    if (captureRef.current || typeof IntersectionObserver !== "function") {
      seenRef.current = true;
      delete board.dataset.waiting;
      return;
    }
    const io = new IntersectionObserver(
      (entries) => {
        if (!entries.some((e) => e.isIntersecting)) return;
        io.disconnect();
        seenRef.current = true;
        enter();
      },
      { threshold: 0.35 },
    );
    io.observe(board);
    return () => io.disconnect();
  }, [showBoard, enter]);

  /* Re-layout: redraw paths without animating. */
  useEffect(() => {
    const board = boardRef.current;
    const svg = svgRef.current;
    if (!showBoard || !board || !svg || typeof ResizeObserver !== "function") return;
    let raf = 0;
    const ro = new ResizeObserver(() => {
      cancelAnimationFrame(raf);
      raf = requestAnimationFrame(() => drawConnectors(board, svg, lookSeed(sel)));
    });
    ro.observe(board);
    return () => {
      cancelAnimationFrame(raf);
      ro.disconnect();
    };
  }, [showBoard, sel]);

  /* Sliding tab underline (transform only). */
  const moveUnderline = useCallback(() => {
    const bar = underlineRef.current;
    const tab = tabRefs.current[sel];
    if (!bar || !tab) return;
    bar.style.transform = `translateX(${tab.offsetLeft}px) scaleX(${tab.offsetWidth / 100})`;
  }, [sel]);

  useLayoutEffect(() => {
    moveUnderline();
    const bar = underlineRef.current;
    if (bar && !bar.dataset.ready) requestAnimationFrame(() => (bar.dataset.ready = ""));
  }, [moveUnderline, looks.length]);

  useEffect(() => {
    const list = tablistRef.current;
    if (!list || typeof ResizeObserver !== "function") return;
    const ro = new ResizeObserver(() => moveUnderline());
    ro.observe(list);
    void document.fonts?.ready.then(() => moveUnderline());
    return () => ro.disconnect();
  }, [moveUnderline]);

  /* Capture hooks (phase 10). */
  useEffect(() => {
    if (!capture) return;
    const api = {
      select: (i: number) => setSelected(Math.max(0, Math.min(looks.length - 1, i))),
      get index() {
        return sel;
      },
    };
    window.__fxLook = api;
    return () => {
      if (window.__fxLook === api) delete window.__fxLook;
    };
  }, [capture, looks.length, sel]);

  const onTabKeyDown = (e: ReactKeyboardEvent<HTMLDivElement>) => {
    const count = looks.length;
    if (count === 0) return;
    const map: Record<string, number> = {
      ArrowRight: (sel + 1) % count,
      ArrowLeft: (sel - 1 + count) % count,
      Home: 0,
      End: count - 1,
    };
    const next = map[e.key];
    if (next === undefined) return;
    e.preventDefault();
    setSelected(next);
    tabRefs.current[next]?.focus();
  };

  if (!loading && !error && looks.length === 0) return null;

  const items = look?.items ?? [];
  const addable = addableItems(current, look);
  const lookTotal = [current, ...items].reduce((s, p) => s + p.price_cents, 0);
  const currentImg = primaryImage(current);

  return (
    <section className="fx-look" aria-labelledby={titleId}>
      <header className="fx-look__head">
        <h2 id={titleId} className="fx-look__title font-display">
          Complete the look
        </h2>
        <span className="fx-ai-chip">Suggested by AI</span>
        <span
          className="fx-tip"
          data-open={tipOpen || undefined}
          onKeyDown={(e) => {
            if (e.key === "Escape") setTipOpen(false);
          }}
          onMouseLeave={() => setTipOpen(false)}
        >
          <button
            type="button"
            className="fx-tip__trigger"
            aria-label="About AI suggestions"
            aria-describedby={tipId}
            onClick={() => setTipOpen((o) => !o)}
            onBlur={() => setTipOpen(false)}
          >
            <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
              <circle cx="12" cy="12" r="9" />
              <path d="M12 11v6M12 7.5v.01" />
            </svg>
          </button>
          <span role="tooltip" id={tipId} className="fx-tip__bubble">
            {AI_TOOLTIP}
          </span>
        </span>
      </header>

      {looks.length > 0 && !error && (
        <div ref={tablistRef} className="fx-tabs" role="tablist" aria-label="Looks" onKeyDown={onTabKeyDown}>
          {looks.map((l, i) => (
            <button
              key={l.index}
              ref={(el) => {
                tabRefs.current[i] = el;
              }}
              id={tabId(i)}
              type="button"
              role="tab"
              className="fx-tab"
              aria-selected={i === sel}
              aria-controls={panelId}
              tabIndex={i === sel ? 0 : -1}
              onClick={() => setSelected(i)}
            >
              <span className="fx-tab__num">Look {i + 1}</span>
              <span className="fx-tab__title">{l.title}</span>
            </button>
          ))}
          <span ref={underlineRef} className="fx-tab-underline" aria-hidden="true" />
        </div>
      )}

      {error ? (
        <div className="fx-look__error" role="alert">
          <p>{STYLIST_ERROR}</p>
          {onRetry && (
            <button type="button" className="fx-btn fx-btn--secondary" onClick={onRetry}>
              Retry
            </button>
          )}
        </div>
      ) : loading ? (
        <div className="fx-look__loading">
          <div className="fx-board" data-count={3} aria-hidden="true">
            <div className="fx-board__anchor">
              <div className="fx-board__tile fx-shimmer" />
            </div>
            {[0, 1, 2].map((k) => (
              <div key={k} className="fx-board__item" data-k={k}>
                <div className="fx-board__tile fx-shimmer" />
                <span className="fx-board__line-skel fx-shimmer" />
              </div>
            ))}
          </div>
          <p className="fx-look__status" role="status">
            Styling…
          </p>
        </div>
      ) : look ? (
        <div id={panelId} role="tabpanel" aria-labelledby={tabId(sel)}>
          <div ref={boardRef} className="fx-board" data-count={Math.min(4, Math.max(1, items.length))}>
            <svg ref={svgRef} className="fx-board__connectors" aria-hidden="true" focusable="false" />
            <figure className="fx-board__anchor" data-look-anchor="">
              <div className="fx-board__tile">
                {currentImg && (
                  <img
                    src={imageUrl(currentImg.path, 640)}
                    alt={currentImg.alt}
                    width={640}
                    height={800}
                    loading="lazy"
                    decoding="async"
                  />
                )}
                <span className="fx-board__anchor-label eyebrow">This piece</span>
              </div>
              <figcaption className="fx-board__meta">
                <span className="fx-board__name">{current.name}</span>
                <span className="fx-board__price tnum">{formatUSD(current.price_cents)}</span>
              </figcaption>
            </figure>
            <ul className="fx-board__items" role="list" aria-label={`Pieces in ${look.title}`}>
              {items.map((p, k) => {
                const img = primaryImage(p);
                const soldOut = !inStock(p);
                return (
                  <li
                    key={`${sel}-${p.id}`}
                    className="fx-board__item"
                    data-look-item=""
                    data-k={k}
                    data-sold-out={soldOut || undefined}
                  >
                    <div className="fx-board__tile">
                      <Link href={productHref(p.slug)} className="fx-board__link" tabIndex={-1} aria-hidden="true">
                        {img && (
                          <img
                            src={imageUrl(img.path, 640)}
                            alt=""
                            width={640}
                            height={800}
                            loading="lazy"
                            decoding="async"
                          />
                        )}
                      </Link>
                      {soldOut && <span className="fx-board__badge eyebrow">Sold out</span>}
                      <button
                        type="button"
                        className="fx-board__add"
                        aria-label={`Quick add ${p.name}`}
                        disabled={soldOut}
                        onClick={() => onQuickAdd(p)}
                      >
                        <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
                          <path d="M12 5v14M5 12h14" />
                        </svg>
                      </button>
                    </div>
                    <div className="fx-board__meta">
                      <Link href={productHref(p.slug)} className="fx-board__name">
                        {p.name}
                      </Link>
                      <span className="fx-board__price tnum">
                        {formatUSD(p.price_cents)}
                        {soldOut && <span className="fx-sr-only"> (sold out)</span>}
                      </span>
                    </div>
                  </li>
                );
              })}
            </ul>
          </div>
          <div className="fx-board__why">
            <p ref={rationaleRef} className="fx-board__rationale">
              {look.rationale}
            </p>
            <div className="fx-board__footer">
              <p className="fx-board__total tnum">
                {items.length + 1} pieces · {formatUSD(lookTotal)}
              </p>
              <button
                type="button"
                className="fx-btn fx-btn--primary"
                disabled={addable.length === 0}
                onClick={() => onAddAll(addable)}
              >
                Add the full look
              </button>
              {footerSlot}
            </div>
          </div>
        </div>
      ) : null}
    </section>
  );
}

export { LookBoard };
